assert.equal(usage.groups.filter(g=>g.accounting_status==='incomplete').length,53);
assert(usage.groups.filter(g=>g.accounting_status==='incomplete').every(g=>g.total_tokens===null&&g.total_api_equivalent_cost_usd===null));
